// Package system exposes platform-level settings that are not scoped to a team.
package system

import (
	"context"
	"encoding/json"
	"errors"
	"fmt"

	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgconn"
	"github.com/jackc/pgx/v5/pgxpool"
)

var (
	// ErrNotInitialized means the baseline settings row is missing.
	ErrNotInitialized = errors.New("system settings are not initialized")
	// ErrNotMigrated means the schema has not been migrated yet.
	ErrNotMigrated = errors.New("database schema has not been migrated")
)

// Repository reads platform-level state from PostgreSQL.
type Repository struct {
	pool *pgxpool.Pool
}

// NewRepository builds a Repository around an existing pool.
func NewRepository(pool *pgxpool.Pool) *Repository {
	return &Repository{pool: pool}
}

// Ping verifies that the database is reachable.
func (r *Repository) Ping(ctx context.Context) error {
	return r.pool.Ping(ctx)
}

// InstallationID returns the stable identifier generated by the baseline
// migration.
func (r *Repository) InstallationID(ctx context.Context) (string, error) {
	var raw []byte
	err := r.pool.QueryRow(ctx, "SELECT value FROM system_settings WHERE key = 'installation_id'").Scan(&raw)
	if errors.Is(err, pgx.ErrNoRows) {
		return "", ErrNotInitialized
	}
	if err != nil {
		return "", fmt.Errorf("read installation id: %w", err)
	}

	var id string
	if err := json.Unmarshal(raw, &id); err != nil {
		return "", fmt.Errorf("decode installation id: %w", err)
	}
	if id == "" {
		return "", ErrNotInitialized
	}
	return id, nil
}

// SchemaVersion returns the highest applied migration version. A missing
// migration table is reported as ErrNotMigrated.
func (r *Repository) SchemaVersion(ctx context.Context) (int64, error) {
	var version int64
	err := r.pool.QueryRow(ctx,
		"SELECT COALESCE(MAX(version_id), 0) FROM goose_db_version WHERE is_applied",
	).Scan(&version)
	if err != nil {
		var pgErr *pgconn.PgError
		if errors.As(err, &pgErr) && pgErr.Code == "42P01" {
			return 0, ErrNotMigrated
		}
		return 0, fmt.Errorf("read schema version: %w", err)
	}
	return version, nil
}
